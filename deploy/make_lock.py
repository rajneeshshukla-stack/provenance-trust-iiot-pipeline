#!/usr/bin/env python3
"""Write deploy/requirements.lock.txt: the complete resolved dependency set of the released requirements.txt
(as installed in pbti:v2-envshim, `pip freeze` in logs/v2envshim_env.log) with the SHA-256 of every distribution
file PyPI lists for each pinned version (pip-compile --generate-hashes style), for
`pip install --require-hashes --no-deps --only-binary=:all:`.
Usage: python3 -I scripts/make_lock.py logs/v2envshim_env.log REPO/requirements.txt deploy/requirements.lock.txt
"""
import json
import re
import sys
import urllib.request

freeze_log, reqs, dst = sys.argv[1], sys.argv[2], sys.argv[3]
pins = []
for line in open(freeze_log):
    m = re.fullmatch(r"([A-Za-z0-9_.\-]+)==([A-Za-z0-9_.\-+]+)\s*", line)
    if m:
        pins.append((m.group(1), m.group(2)))
top = {}
for line in open(reqs):
    line = line.split("#")[0].strip()
    if "==" in line:
        n, v = line.split("==")
        top[n.strip().lower()] = v.strip()
frozen = {n.lower(): v for n, v in pins}
for n, v in top.items():  # the released top-level pins must be exactly what was installed
    assert frozen.get(n) == v, (n, v, frozen.get(n))
out = ["# Complete, hash-pinned dependency set for deploy/Dockerfile.v3 (generated by scripts/make_lock.py).",
       "# Top-level versions are exactly those of the released requirements.txt; transitive versions are the ones",
       "# pip resolved for that file in pbti:v2-envshim on 2026-11-04 (python 3.13.18, linux/amd64).",
       "# Every distribution file PyPI lists for each pinned version is hashed (any platform can verify).", ""]
for name, ver in sorted(pins, key=lambda p: p[0].lower()):
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json", timeout=60) as r:
        d = json.load(r)
    hashes = sorted({f["digests"]["sha256"] for f in d["urls"]})
    assert hashes, (name, ver)
    out.append("# top-level (requirements.txt)" if name.lower() in top else "# transitive")
    out.append(f"{name}=={ver} \\")
    out += [f"    --hash=sha256:{h} \\" for h in hashes[:-1]] + [f"    --hash=sha256:{hashes[-1]}"]
    print(f"{name}=={ver}: {len(hashes)} files", file=sys.stderr)
open(dst, "w").write("\n".join(out) + "\n")
print(f"wrote {dst}: {len(pins)} packages ({len(top)} top-level)", file=sys.stderr)
