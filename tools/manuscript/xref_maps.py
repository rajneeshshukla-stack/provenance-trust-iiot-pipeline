"""Cross-document reference maps for the article and its supplement.

Usage: python3 -I xref_maps.py PAPER_DIR [--check]

Reads supplementary.aux and main.aux (if present) and writes
  generated/supp_xref.tex  -- \\suppref@<label> for every label of the supplement, plus
                              last:table, last:figure and range:<section label> (e.g. "Tables S2--S5 and Figure S1")
  generated/main_xref.tex  -- \\mainref@<label> for every label of the article
so that the article can write Table~\\Sref{tab:S-env} and the supplement Section~\\Mref{sec:pipelines}. Both files are
plain macro definitions, so each document still compiles on its own. With --check the script exits 1 if a map would
change (the build is not yet stable).
"""
import re
import sys
from pathlib import Path

D = Path(sys.argv[1])
CHECK = "--check" in sys.argv
LABEL = re.compile(r"\\newlabel\{([^}]+)\}\{\{([^}]*)\}")


def labels(aux):
    out = []
    if aux.exists():
        for m in LABEL.finditer(aux.read_text(errors="replace")):
            if not m.group(1).endswith("@cref"):
                out.append((m.group(1), m.group(2)))
    return out


def plural(kind, nums):
    if not nums:
        return ""
    if len(nums) == 1:
        return f"{kind} {nums[0]}"
    if len(nums) == 2:
        return f"{kind}s {nums[0]} and {nums[1]}"
    return f"{kind}s {nums[0]}--{nums[-1]}"


def write(path, prefix, items):
    body = "% generated by tools/xref_maps.py -- do not edit\n" + "".join(
        f"\\expandafter\\def\\csname {prefix}@{k}\\endcsname{{{v}}}\n" for k, v in items)
    old = path.read_text() if path.exists() else ""
    if old != body:
        if CHECK:
            return False
        path.write_text(body)
    return True


supp = labels(D / "supplementary.aux")
items = list(supp)
tabs = [v for k, v in supp if k.startswith("tab:")]
figs = [v for k, v in supp if k.startswith("fig:")]
if tabs:
    items.append(("last:table", tabs[-1]))
if figs:
    items.append(("last:figure", figs[-1]))
# ranges per supplementary section (labels appear in document order in the aux file)
cur, acc = None, {}
for k, v in supp:
    if k.startswith("sec:S-"):
        cur = k
        acc[cur] = {"tab": [], "fig": []}
    elif cur and k.startswith("tab:"):
        acc[cur]["tab"].append(v)
    elif cur and k.startswith("fig:"):
        acc[cur]["fig"].append(v)
for sec, d in acc.items():
    parts = [p for p in (plural("Table", d["tab"]), plural("Figure", d["fig"])) if p]
    items.append((f"range:{sec}", " and ".join(parts) if len(parts) == 2 else (parts[0] if parts else "text only")))
ok1 = write(D / "generated" / "supp_xref.tex", "suppref", items)
ok2 = write(D / "generated" / "main_xref.tex", "mainref", labels(D / "main.aux"))
if CHECK:
    print("stable" if (ok1 and ok2) else "changed")
    sys.exit(0 if (ok1 and ok2) else 1)
print(f"supplement labels: {len(supp)} (tables {len(tabs)}, figures {len(figs)}); article labels: {len(labels(D / 'main.aux'))}")
