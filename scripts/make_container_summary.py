#!/usr/bin/env python3
"""Write results/containers/v3_final/SUMMARY.md from the container check logs (no hand-typed results).

Inputs (written by the container check scripts in deploy/ and the workspace script run_container_v3.sh):
logs/build.log, logs/image_inspect.json, logs/checks_summary.txt, logs/v3final_*.log.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "results" / "containers" / "v3_final"
L = D / "logs"


def read(name):
    p = L / name
    return p.read_text(errors="replace") if p.exists() else ""


def exit_code(log):
    m = re.search(r"# exit_code:\s*(-?\d+)", log)
    return int(m.group(1)) if m else None


build = read("build.log")
build_exit = re.search(r"build_exit=(\d+)", build)
insp = []
try:
    insp = json.loads(read("image_inspect.json") or "[]")
except json.JSONDecodeError:
    pass
img = insp[0] if insp else {}
size_mb = img.get("Size", 0) / 1e6
health = img.get("Config", {}).get("Healthcheck", {}).get("Test")
user = img.get("Config", {}).get("User")
mt = read("v3final_make_test.log")
mt_line = re.search(r"^(\d+ passed.*?) in [\d.]+s", mt, re.M)
smoke = read("v3final_smoke.log")
smoke_out = [ln for ln in smoke.splitlines() if ln and not ln.startswith("#")]
e2e = read("v3final_e2e.log")
e2e_sys = sorted(set(re.findall(r"rate \d+ (\w+):", e2e)))
hs, he = read("v3final_hardened_smoke.log"), read("v3final_hardened_e2e.log")
hc = read("v3final_healthcheck.log")
hc_status = re.findall(r"status: (\w+)", hc)
checks = read("checks_summary.txt")
tb = any("Traceback" in t for t in (smoke, e2e, hs, he, mt))


def ok(c):
    return "exit 0" if c == 0 else f"exit {c}"


rows = [
    ("build", f"exit {build_exit.group(1)} (`logs/build.log`)" if build_exit else "no build result"),
    ("environment (`id`, versions, `pip freeze`)", ok(exit_code(read("v3final_env.log")))),
    ("`make test`", (mt_line.group(1) if mt_line else "no pytest summary") + f"; {ok(exit_code(mt))}"),
    ("smoke run (S01, PBTI, seed 1)", f"{ok(exit_code(smoke))}, output `{' '.join(smoke_out)}` (non-legitimate, missing)"),
    ("MQTT/TLS end-to-end smoke at 20 msg/s", f"{ok(exit_code(e2e))}, pipelines {', '.join(e2e_sys)}"),
    ("hardened runtime (`--read-only --tmpfs /tmp --cap-drop ALL --security-opt no-new-privileges`): smoke",
     ok(exit_code(hs))),
    ("hardened runtime: end-to-end", ok(exit_code(he))),
    ("health check", hc_status[-1] if hc_status else "no result"),
]
C = D / "compose"
for fname, lab in (("compose_run_make_test.log", "`docker compose run --rm pbti make test` (results volume seeded with the stored results)"),
                   ("compose_run_make_test_empty_volume.log", "`docker compose run --rm pbti make test` (empty results volume)")):
    if (C / fname).exists():
        txt = (C / fname).read_text(errors="replace")
        summ = re.findall(r"^(\d+ (?:failed|passed).*?) in [\d.]+s", txt, re.M)
        ex = re.findall(r"exit=(\d+)", txt)
        rows.append((lab, (summ[-1] if summ else "no pytest summary") + (f"; exit {ex[-1]}" if ex else "")))
if (C / "compose_config.txt").exists():
    rows.append(("`docker compose config`", "valid" if "services:" in (C / "compose_config.txt").read_text() else "invalid"))
out = ["# V3 container validation (final V3 source)", "",
       f"* Image: `pbti:v3-final`, id `{img.get('Id', 'n/a')}`, {size_mb:.1f} MB, created {img.get('Created', 'n/a')}; built from the "
       "final V3 repository with `deploy/Dockerfile.v3` (base `python:3.13.18-slim-trixie` pinned by digest, pinned Debian "
       f"packages, hash-locked Python dependencies installed with `--require-hashes`, runtime user `{user}`, health check `{health}`).",
       "* Environment shim: the study environment re-signs outbound TLS, so the proxy CA was passed to the pip step as a "
       "BuildKit secret (`--secret id=pipca,...`); it is not stored in any layer (`logs/v3final_image_history.txt`).",
       "* Checks (container checks with a CPU limit, logs in `logs/`; compose runs without one, logs in `compose/`); generated by `scripts/make_container_summary.py`:", "",
       "| Check | Result |", "|---|---|"]
out += [f"| {a} | {b} |" for a, b in rows]
out += ["", f"Tracebacks in the check logs: {'yes' if tb else 'none'}. Latencies in these logs come from a shared host with a "
        "CPU limit and are not performance results. Raw summary of the check scripts:", "", "```", checks.strip(), "```"]
(D / "SUMMARY.md").write_text("\n".join(out) + "\n")
print("written", D / "SUMMARY.md")
